// node xlam/build-xlam.js  -> xlam/out/{ribbon.xml, Dispatch.bas, images/*.png}; then make-xlam.ps1 builds the .xlam
const fs = require('fs'), path = require('path'), cp = require('child_process');
const { TABS } = require('./xlam-tools.js');

const out = path.join(__dirname, 'out'), img = path.join(out, 'images');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(img, { recursive: true });
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const safe = s => s.replace(/[^A-Za-z0-9]/g, '_');

const icons = {}, cases = [];
let tabs = '';
TABS.forEach((tab, ti) => {
  const order = [], byGroup = {};
  tab.groups.forEach(t => { (byGroup[t[0]] = byGroup[t[0]] || (order.push(t[0]), [])).push(t); });
  let groups = '';
  order.forEach((gname, gi) => {
    const done = new Set();
    let body = '';
    const btn = (t, big) => {
      icons['x_' + t[2]] = t[5];
      cases.push(`    Case "${t[2]}": ${t[6]}`);
      return `<button id="p_${t[2]}" label="${esc(t[3])}" screentip="${esc(t[3])}" supertip="${esc(t[4])}" image="x_${t[2]}" onAction="OnAction"${big ? ' size="large"' : ''}/>`;
    };
    byGroup[gname].forEach(t => {
      if (!t[1]) return (body += btn(t, true));
      if (done.has(t[1])) return;
      done.add(t[1]);
      const items = byGroup[gname].filter(x => x[1] === t[1]);
      icons['m_' + safe(t[1]) + '_' + ti + gi] = t[5];
      body += `<menu id="m_${ti}_${gi}_${safe(t[1])}" label="${esc(t[1])}" size="large" image="m_${safe(t[1])}_${ti}${gi}">${items.map(x => btn(x, false)).join('')}</menu>`;
    });
    groups += `<group id="g_${ti}_${gi}" label="${esc(gname)}">${body}</group>`;
  });
  const pos = ti === 0 ? 'insertAfterMso="TabHome"' : `insertAfterQ="q:tab_${TABS[ti - 1].id}"`;
  tabs += `<tab idQ="q:tab_${tab.id}" label="${esc(tab.label)}" ${pos}>${groups}</tab>`;
});
fs.writeFileSync(path.join(out, 'ribbon.xml'),
  `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<customUI xmlns="http://schemas.microsoft.com/office/2009/07/customui" xmlns:q="Pro100x"><ribbon><tabs>${tabs}</tabs></ribbon></customUI>`);

const dispatch = `Attribute VB_Name = "Dispatch"
Option Explicit

' GENERATED by xlam/build-xlam.js - do not edit
Public Sub OnAction(ByVal control As IRibbonControl)
    On Error GoTo Fail
    Application.ScreenUpdating = False
    RunTool Mid$(control.Id, 3)
    Application.ScreenUpdating = True
    Exit Sub
Fail:
    Application.ScreenUpdating = True
    Application.CutCopyMode = False
    MsgBox Err.Description, vbExclamation, "Excel 100x Pro"
End Sub

Public Sub RunTool(ByVal id As String)
    Select Case id
${cases.join(String.fromCharCode(10))}
    End Select
End Sub

' Used by xlam/test-xlam.ps1: returns the error text instead of showing a dialog
Public Function TestTool(ByVal id As String) As String
    On Error GoTo Fail
    RunTool id
    TestTool = "ok"
    Exit Function
Fail:
    TestTool = "ERR " & Err.Number & ": " & Err.Description
End Function
`;
fs.writeFileSync(path.join(out, 'Dispatch.bas'), dispatch.replace(/\r?\n/g, '\r\n'), 'ascii');

// every dispatched sub must exist as Public in a hand-written module
const vba = fs.readdirSync(__dirname).filter(f => f.endsWith('.bas')).map(f => fs.readFileSync(path.join(__dirname, f), 'latin1')).join('\n');
const have = new Set([...vba.matchAll(/^Public (?:Sub|Function) (\w+)/gm)].map(m => m[1]));
const missing = [...new Set(cases.map(c => c.split(': ')[1].split(/[ (]/)[0]))].filter(n => !have.has(n));
if (missing.length) console.warn('MISSING VBA subs:', missing.join(', '));

fs.writeFileSync(path.join(out, 'icons.json'), JSON.stringify(icons));
cp.execFileSync('python', [path.join(__dirname, '..', 'build', 'gen_icons.py'), path.join(out, 'icons.json'), img], { stdio: 'inherit' });
fs.readdirSync(img).filter(f => !/_32\.png$/.test(f)).forEach(f => fs.unlinkSync(path.join(img, f)));
console.log(`ribbon: ${TABS.length} tabs, ${cases.length} tools, ${Object.keys(icons).length} icons`);
